// Builds src/densities.ts from USDA FoodData Central SR Legacy portion weights.
//
// Download and unzip the SR Legacy CSV release, then run:
//   node --import tsx packages/db/scripts/build-densities.ts <csv-directory>
// https://fdc.nal.usda.gov/download-datasets (public domain)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { normaliseItem } from "../src/ingredients";

type Source = {
  fdcId: number;
  portion?: string;
  /** Poured rather than spooned: metric shows millilitres, not grams. */
  liquid?: boolean;
  items: string[];
};

const here = dirname(fileURLToPath(import.meta.url));
const directory = process.argv[2];
if (!directory) throw new Error("Pass the SR Legacy CSV directory");

function readCsv(name: string) {
  const [header, ...rows] = readFileSync(
    join(directory as string, name),
    "utf8",
  )
    .trim()
    .split(/\r?\n/)
    .map((line) =>
      [...line.matchAll(/"((?:[^"]|"")*)"/g)].map((m) =>
        (m[1] ?? "").replace(/""/g, '"'),
      ),
    );
  return rows.map((row) =>
    Object.fromEntries((header ?? []).map((key, i) => [key, row[i] ?? ""])),
  );
}

// US customary sizes, which USDA portions use.
const usMillilitres = { cup: 236.588, tablespoon: 14.787, teaspoon: 4.929 };
const spoonPrefixes: [string, keyof typeof usMillilitres][] = [
  ["cup", "cup"],
  ["tbsp", "tablespoon"],
  ["tablespoon", "tablespoon"],
  ["tsp", "teaspoon"],
  ["teaspoon", "teaspoon"],
];

const foods = new Map(
  readCsv("food.csv").map((row) => [row.fdc_id, row.description]),
);
const units = new Map(
  readCsv("measure_unit.csv").map((row) => [row.id, row.name]),
);
const portions = readCsv("food_portion.csv").flatMap((row) => {
  const modifier = (row.modifier ?? "").toLowerCase();
  let unit = units.get(row.measure_unit_id ?? "") as string | undefined;
  if (!unit || !(unit in usMillilitres))
    unit = spoonPrefixes.find(([prefix]) => modifier.startsWith(prefix))?.[1];
  const amount = Number(row.amount);
  const grams = Number(row.gram_weight);
  if (!unit || !(amount > 0) || !(grams > 0)) return [];
  const millilitres =
    usMillilitres[unit as keyof typeof usMillilitres] * amount;
  return [
    {
      fdcId: Number(row.fdc_id),
      label: `${row.amount} ${unit} ${row.modifier}`
        .toLowerCase()
        .replace(/[,()]/g, " ")
        .replace(/\s+/g, " ")
        .trim(),
      gramsPerMl: grams / millilitres,
    },
  ];
});

const { sources } = JSON.parse(
  readFileSync(join(here, "density-sources.json"), "utf8"),
) as { sources: Source[] };

const entries = new Map<
  string,
  { density: number; liquid: boolean; note: string }
>();
// Not in SR Legacy with a cup measure.
entries.set("water", { density: 1, liquid: true, note: "water" });
for (const source of sources) {
  // Cup measures are the most precise; "packed" must not match "unpacked".
  const wanted = source.portion?.toLowerCase();
  const match = portions
    .filter(
      (portion) =>
        portion.fdcId === source.fdcId &&
        (!wanted || ` ${portion.label}`.includes(` ${wanted}`)),
    )
    .sort(
      (a, b) =>
        Number(b.label.startsWith("1 cup")) -
          Number(a.label.startsWith("1 cup")) ||
        Number(b.label.includes("cup")) - Number(a.label.includes("cup")),
    )[0];
  if (!match)
    throw new Error(`No portion for ${source.fdcId} ${source.portion ?? ""}`);
  const note = `${foods.get(String(source.fdcId))}, ${match.label.trim()} (FDC ${source.fdcId})`;
  for (const item of source.items) {
    const key = normaliseItem(item);
    const existing = entries.get(key);
    if (existing?.note === note) continue;
    if (existing) throw new Error(`Duplicate item: ${key}`);
    entries.set(key, {
      density: Number(match.gramsPerMl.toFixed(3)),
      liquid: source.liquid ?? false,
      note,
    });
  }
}

const sorted = [...entries].sort(([a], [b]) => a.localeCompare(b));
const lines = sorted.map(
  ([item, { density, note }]) =>
    `  ${JSON.stringify(item)}: ${density}, // ${note.replace(/\s+/g, " ")}`,
);
const liquids = sorted
  .filter(([, entry]) => entry.liquid)
  .map(([item]) => `  ${JSON.stringify(item)},`);
writeFileSync(
  join(here, "../src/densities.ts"),
  `// Generated by scripts/build-densities.ts from USDA FoodData Central
// SR Legacy portion weights. Edit scripts/density-sources.json, not this file.

/** Grams per millilitre, keyed by normalised ingredient name. */
export const densities: Record<string, number> = {
${lines.join("\n")}
};

/** Poured ingredients, shown in millilitres rather than grams. */
export const liquids = new Set([
${liquids.join("\n")}
]);
`,
);
console.log(`Wrote ${entries.size} densities`);
